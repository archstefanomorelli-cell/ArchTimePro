create or replace function public.get_entries_for_export()
returns table (
  id uuid,
  studio_id uuid,
  project_id uuid,
  project_name text,
  task text,
  duration numeric,
  user_email text,
  user_name text,
  rate numeric,
  notes text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  caller_studio uuid;
  caller_email text;
  caller_is_admin boolean;
begin
  if auth.uid() is null then
    raise exception 'Utente non autenticato';
  end if;

  caller_studio := public.get_my_studio_id();
  caller_is_admin := public.is_admin();
  select p.email into caller_email from public.profiles p where p.id = auth.uid();

  if caller_studio is null or caller_email is null then
    raise exception 'Profilo non valido';
  end if;

  return query
  select
    entry.id,
    entry.studio_id,
    entry.project_id,
    entry.project_name,
    entry.task,
    entry.duration::numeric,
    entry.user_email,
    entry.user_name,
    case when caller_is_admin then entry.rate::numeric else null::numeric end,
    entry.notes,
    entry.created_at
  from public.entries entry
  where entry.studio_id = caller_studio
    and (caller_is_admin or entry.user_email = caller_email)
  order by entry.created_at desc;
end;
$$;

