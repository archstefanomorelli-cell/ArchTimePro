create or replace function public.get_my_profile_for_app()
returns table (
  id uuid,
  studio_id uuid,
  full_name text,
  email text,
  role text,
  is_owner boolean,
  hourly_cost numeric,
  active_timer_start text,
  active_timer_project text,
  active_timer_task text,
  active_timer_notes text,
  active_timer_reminder_sent_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select
    p.id,
    p.studio_id,
    p.full_name,
    p.email,
    p.role::text,
    coalesce(p.is_owner, false),
    case when coalesce(p.is_owner, false) or p.role = 'admin' then p.hourly_cost else null end,
    to_jsonb(p) ->> 'active_timer_start',
    to_jsonb(p) ->> 'active_timer_project',
    to_jsonb(p) ->> 'active_timer_task',
    to_jsonb(p) ->> 'active_timer_notes',
    nullif(to_jsonb(p) ->> 'active_timer_reminder_sent_at', '')::timestamptz
  from public.profiles p
  where p.id = auth.uid();
$$;

