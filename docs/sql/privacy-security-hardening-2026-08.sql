create or replace function public.join_studio_with_code(invite_studio_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_profile public.profiles%rowtype;
begin
  if auth.uid() is null or invite_studio_id is null then
    raise exception 'Invito non valido';
  end if;

  select * into current_profile
  from public.profiles
  where id = auth.uid()
  for update;

  if current_profile.id is null or current_profile.studio_id is not null then
    raise exception 'Profilo non disponibile per questo invito';
  end if;

  if not exists (select 1 from public.studios where id = invite_studio_id) then
    raise exception 'Studio non trovato';
  end if;

  update public.profiles
  set studio_id = invite_studio_id, role = 'staff', is_owner = false
  where id = auth.uid();
end;
$$;

create or replace function public.set_my_hourly_cost(new_hourly_cost numeric)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_profile public.profiles%rowtype;
begin
  select * into current_profile
  from public.profiles
  where id = auth.uid()
  for update;

  if current_profile.id is null
     or not (coalesce(current_profile.is_owner, false) or current_profile.role = 'admin') then
    raise exception 'Permesso negato';
  end if;

  if new_hourly_cost is null or new_hourly_cost < 0 then
    raise exception 'Costo orario non valido';
  end if;

  if current_profile.hourly_cost is distinct from new_hourly_cost then
    update public.profile_hourly_cost_history
    set effective_to = now()
    where profile_id = current_profile.id and effective_to is null;

    insert into public.profile_hourly_cost_history (
      profile_id, studio_id, hourly_cost, effective_from, changed_by
    ) values (
      current_profile.id, current_profile.studio_id, new_hourly_cost, now(), auth.uid()
    );

    update public.profiles
    set hourly_cost = new_hourly_cost
    where id = current_profile.id;

    insert into public.audit_log (
      studio_id, actor_id, entity_type, entity_id, action, old_data, new_data
    ) values (
      current_profile.studio_id,
      auth.uid(),
      'profile',
      current_profile.id::text,
      'update',
      jsonb_build_object('hourly_cost', current_profile.hourly_cost),
      jsonb_build_object('hourly_cost', new_hourly_cost)
    );
  end if;
end;
$$;

create or replace function public.update_team_member_for_app(
  target_profile_id uuid,
  target_full_name text,
  target_hourly_cost numeric,
  target_role text,
  transfer_ownership boolean default false
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  caller_profile public.profiles%rowtype;
  old_profile public.profiles%rowtype;
  final_role text;
  final_owner boolean;
begin
  select * into caller_profile
  from public.profiles
  where id = auth.uid()
  for update;

  if caller_profile.id is null
     or not (coalesce(caller_profile.is_owner, false) or caller_profile.role = 'admin') then
    raise exception 'Permesso negato';
  end if;

  select * into old_profile
  from public.profiles
  where id = target_profile_id
    and studio_id = caller_profile.studio_id
  for update;

  if old_profile.id is null then
    raise exception 'Collaboratore non trovato';
  end if;

  if nullif(trim(target_full_name), '') is null then
    raise exception 'Nome obbligatorio';
  end if;

  if target_hourly_cost is null or target_hourly_cost < 0 then
    raise exception 'Costo orario non valido';
  end if;

  if target_role not in ('admin', 'staff', 'inactive') then
    raise exception 'Ruolo non valido';
  end if;

  if coalesce(old_profile.is_owner, false) and old_profile.id <> caller_profile.id then
    raise exception 'Solo il proprietario può modificare il proprio profilo';
  end if;

  if not coalesce(caller_profile.is_owner, false)
     and (coalesce(old_profile.is_owner, false) or old_profile.role = 'admin')
     and old_profile.id <> caller_profile.id then
    raise exception 'Un admin non può modificare owner o altri admin';
  end if;

  if old_profile.id = caller_profile.id
     and target_role is distinct from old_profile.role
     and not transfer_ownership then
    raise exception 'Non puoi modificare il tuo ruolo';
  end if;

  final_role := target_role;
  final_owner := coalesce(old_profile.is_owner, false);

  if transfer_ownership then
    if not coalesce(caller_profile.is_owner, false)
       or old_profile.id = caller_profile.id then
      raise exception 'Trasferimento di proprietà non consentito';
    end if;

    update public.profiles
    set is_owner = false, role = 'admin'
    where id = caller_profile.id;

    insert into public.audit_log (
      studio_id, actor_id, entity_type, entity_id, action, old_data, new_data
    ) values (
      caller_profile.studio_id,
      auth.uid(),
      'profile',
      caller_profile.id::text,
      'update',
      jsonb_build_object('role', caller_profile.role, 'is_owner', caller_profile.is_owner),
      jsonb_build_object('role', 'admin', 'is_owner', false)
    );

    final_role := 'admin';
    final_owner := true;
  elsif coalesce(old_profile.is_owner, false) then
    final_role := 'admin';
    final_owner := true;
  else
    final_owner := false;
  end if;

  if old_profile.hourly_cost is distinct from target_hourly_cost then
    update public.profile_hourly_cost_history
    set effective_to = now()
    where profile_id = old_profile.id and effective_to is null;

    insert into public.profile_hourly_cost_history (
      profile_id, studio_id, hourly_cost, effective_from, changed_by
    ) values (
      old_profile.id,
      old_profile.studio_id,
      target_hourly_cost,
      now(),
      auth.uid()
    );
  end if;

  update public.profiles
  set
    full_name = trim(target_full_name),
    hourly_cost = target_hourly_cost,
    role = final_role,
    is_owner = final_owner
  where id = old_profile.id;

  insert into public.audit_log (
    studio_id, actor_id, entity_type, entity_id, action, old_data, new_data
  ) values (
    old_profile.studio_id,
    auth.uid(),
    'profile',
    old_profile.id::text,
    'update',
    jsonb_build_object(
      'full_name', old_profile.full_name,
      'hourly_cost', old_profile.hourly_cost,
      'role', old_profile.role,
      'is_owner', old_profile.is_owner
    ),
    jsonb_build_object(
      'full_name', trim(target_full_name),
      'hourly_cost', target_hourly_cost,
      'role', final_role,
      'is_owner', final_owner
    )
  );
end;
$$;

create or replace function public.get_hourly_cost_at(
  target_profile_id uuid,
  effective_at timestamptz
)
returns numeric
language sql
security definer
set search_path = public
as $$
  select coalesce(
    (
      select h.hourly_cost
      from public.profile_hourly_cost_history h
      where h.profile_id = target_profile_id
        and h.effective_from <= coalesce(effective_at, now())
        and (h.effective_to is null or h.effective_to > coalesce(effective_at, now()))
      order by h.effective_from desc
      limit 1
    ),
    (select p.hourly_cost from public.profiles p where p.id = target_profile_id),
    0
  );
$$;

revoke all on function public.get_hourly_cost_at(uuid, timestamptz) from public, anon, authenticated;

create or replace function public.create_entry_for_app(
  entry_project_id uuid,
  entry_task text,
  entry_duration numeric,
  entry_notes text default '',
  entry_created_at timestamptz default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  caller_profile public.profiles%rowtype;
  target_project public.projects%rowtype;
  new_entry_id uuid;
  effective_at timestamptz;
  effective_cost numeric;
begin
  if auth.uid() is null then raise exception 'Utente non autenticato'; end if;
  if entry_project_id is null then raise exception 'Progetto obbligatorio'; end if;
  if entry_duration is null or entry_duration <= 0 then raise exception 'Durata non valida'; end if;

  select * into caller_profile from public.profiles where id = auth.uid();
  if caller_profile.id is null or caller_profile.studio_id is null then
    raise exception 'Profilo non valido';
  end if;

  select * into target_project
  from public.projects
  where id = entry_project_id
    and studio_id = caller_profile.studio_id
    and coalesce(is_archived, false) = false;

  if target_project.id is null then raise exception 'Progetto non trovato o archiviato'; end if;

  effective_at := coalesce(entry_created_at, now());
  effective_cost := public.get_hourly_cost_at(caller_profile.id, effective_at);

  insert into public.entries (
    studio_id, project_id, project_name, task, duration,
    user_email, user_name, rate, notes, created_at
  ) values (
    caller_profile.studio_id,
    target_project.id,
    target_project.name,
    coalesce(nullif(trim(entry_task), ''), 'Generico'),
    entry_duration,
    caller_profile.email,
    caller_profile.full_name,
    effective_cost * entry_duration,
    coalesce(entry_notes, ''),
    effective_at
  ) returning id into new_entry_id;

  return new_entry_id;
end;
$$;

create or replace function public.update_entry_for_app(
  entry_id uuid,
  entry_project_id uuid,
  entry_task text,
  entry_duration numeric,
  entry_notes text default '',
  entry_created_at timestamptz default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  caller_profile public.profiles%rowtype;
  target_entry public.entries%rowtype;
  target_project public.projects%rowtype;
  effective_at timestamptz;
  effective_cost numeric;
begin
  if auth.uid() is null then raise exception 'Utente non autenticato'; end if;
  if entry_id is null then raise exception 'Attività obbligatoria'; end if;
  if entry_project_id is null then raise exception 'Progetto obbligatorio'; end if;
  if entry_duration is null or entry_duration <= 0 then raise exception 'Durata non valida'; end if;

  select * into caller_profile from public.profiles where id = auth.uid();
  if caller_profile.id is null or caller_profile.studio_id is null then
    raise exception 'Profilo non valido';
  end if;

  select * into target_entry
  from public.entries
  where id = entry_id and studio_id = caller_profile.studio_id;

  if target_entry.id is null then raise exception 'Attività non trovata'; end if;
  if target_entry.user_email is distinct from caller_profile.email then
    raise exception 'Puoi modificare solo le attività inserite da te';
  end if;

  select * into target_project
  from public.projects
  where id = entry_project_id
    and studio_id = caller_profile.studio_id
    and coalesce(is_archived, false) = false;

  if target_project.id is null then raise exception 'Progetto non trovato o archiviato'; end if;

  effective_at := coalesce(entry_created_at, target_entry.created_at);
  effective_cost := coalesce(
    target_entry.rate / nullif(target_entry.duration, 0),
    public.get_hourly_cost_at(caller_profile.id, effective_at)
  );

  update public.entries
  set
    project_id = target_project.id,
    project_name = target_project.name,
    task = coalesce(nullif(trim(entry_task), ''), 'Generico'),
    duration = entry_duration,
    notes = coalesce(entry_notes, ''),
    created_at = effective_at,
    user_email = caller_profile.email,
    user_name = caller_profile.full_name,
    rate = effective_cost * entry_duration
  where id = target_entry.id;
end;
$$;

create or replace function public.audit_operational_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  row_before jsonb;
  row_after jsonb;
  audit_studio_id uuid;
  audit_entity_id text;
begin
  delete from public.audit_log
  where created_at < now() - interval '24 months';

  row_before := case when tg_op = 'INSERT' then null else to_jsonb(old) end;
  row_after := case when tg_op = 'DELETE' then null else to_jsonb(new) end;
  audit_studio_id := coalesce(
    nullif(row_after ->> 'studio_id', '')::uuid,
    nullif(row_before ->> 'studio_id', '')::uuid
  );
  audit_entity_id := coalesce(row_after ->> 'id', row_before ->> 'id');

  insert into public.audit_log (
    studio_id, actor_id, entity_type, entity_id, action, old_data, new_data
  ) values (
    audit_studio_id,
    auth.uid(),
    tg_table_name,
    audit_entity_id,
    lower(tg_op),
    row_before,
    row_after
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

