begin;

create table if not exists public.legal_acceptances (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  terms_version text not null,
  privacy_version text not null,
  accepted_at timestamptz not null default now(),
  source text not null default 'signup',
  unique (user_id, terms_version, privacy_version)
);

alter table public.legal_acceptances enable row level security;
revoke all on public.legal_acceptances from anon, authenticated;

create or replace function public.capture_legal_acceptance()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  accepted_at_value timestamptz;
  terms_value text;
  privacy_value text;
begin
  terms_value := nullif(new.raw_user_meta_data ->> 'terms_version', '');
  privacy_value := nullif(new.raw_user_meta_data ->> 'privacy_version', '');

  if terms_value is null or privacy_value is null then
    return new;
  end if;

  begin
    accepted_at_value := coalesce(
      nullif(new.raw_user_meta_data ->> 'legal_accepted_at', '')::timestamptz,
      now()
    );
  exception when others then
    accepted_at_value := now();
  end;

  insert into public.legal_acceptances (
    user_id,
    terms_version,
    privacy_version,
    accepted_at,
    source
  ) values (
    new.id,
    terms_value,
    privacy_value,
    accepted_at_value,
    'signup'
  )
  on conflict (user_id, terms_version, privacy_version) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_legal_acceptance on auth.users;
create trigger on_auth_user_legal_acceptance
after insert on auth.users
for each row execute function public.capture_legal_acceptance();

create or replace function public.has_accepted_legal_documents(
  requested_terms_version text,
  requested_privacy_version text
)
returns boolean
language sql
security definer
set search_path = public
as $$
  select auth.uid() is not null and exists (
    select 1
    from public.legal_acceptances acceptance
    where acceptance.user_id = auth.uid()
      and acceptance.terms_version = requested_terms_version
      and acceptance.privacy_version = requested_privacy_version
  );
$$;

create or replace function public.accept_legal_documents(
  accepted_terms_version text,
  accepted_privacy_version text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Utente non autenticato';
  end if;
  if nullif(trim(accepted_terms_version), '') is null
    or nullif(trim(accepted_privacy_version), '') is null then
    raise exception 'Versione dei documenti non valida';
  end if;

  insert into public.legal_acceptances (
    user_id, terms_version, privacy_version, accepted_at, source
  ) values (
    auth.uid(),
    trim(accepted_terms_version),
    trim(accepted_privacy_version),
    now(),
    'in_app_update'
  )
  on conflict (user_id, terms_version, privacy_version) do nothing;
end;
$$;

create table if not exists public.profile_hourly_cost_history (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  studio_id uuid not null references public.studios(id) on delete cascade,
  hourly_cost numeric not null check (hourly_cost >= 0),
  effective_from timestamptz not null default now(),
  effective_to timestamptz,
  changed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check (effective_to is null or effective_to > effective_from)
);

create index if not exists profile_hourly_cost_history_lookup_idx
on public.profile_hourly_cost_history(profile_id, effective_from desc);

alter table public.profile_hourly_cost_history enable row level security;
revoke all on public.profile_hourly_cost_history from anon, authenticated;

drop policy if exists "profile_cost_history_admin_select" on public.profile_hourly_cost_history;
create policy "profile_cost_history_admin_select"
on public.profile_hourly_cost_history
for select
to authenticated
using (public.is_admin() and studio_id = public.get_my_studio_id());

grant select on public.profile_hourly_cost_history to authenticated;

insert into public.profile_hourly_cost_history (
  profile_id,
  studio_id,
  hourly_cost,
  effective_from,
  changed_by
)
select
  p.id,
  p.studio_id,
  coalesce(p.hourly_cost, 0),
  now(),
  p.id
from public.profiles p
where p.studio_id is not null
  and not exists (
    select 1
    from public.profile_hourly_cost_history h
    where h.profile_id = p.id
  );

